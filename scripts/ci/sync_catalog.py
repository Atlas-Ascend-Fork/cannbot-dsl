"""Generate CI and Native build configuration from operator and network catalogs.

Run --write after editing catalog/operators.json or net/*/network.json.
Run --check to verify generated files. Only the Python standard library is required."""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CATALOG = Path("catalog/operators.json")
LICENSE_HEADER = '# Copyright (c) 2026 Huawei Technologies Co., Ltd.\n# This program is free software, you can redistribute it and/or modify it under the terms and conditions of\n# CANN Open Software License Agreement Version 2.0 (the "License").\n# Please refer to the License for details. You may not use this file except in compliance with the License.\n# THIS SOFTWARE IS PROVIDED ON AN "AS IS" BASIS, WITHOUT WARRANTIES OF ANY KIND, EITHER EXPRESS OR IMPLIED,\n# INCLUDING BUT NOT LIMITED TO NON-INFRINGEMENT, MERCHANTABILITY, OR FITNESS FOR A PARTICULAR PURPOSE.\n# See LICENSE in the root of the software repository for the full text of the License.\n'
GENERATED = (
    LICENSE_HEADER
    + "# Generated by scripts/ci/sync_catalog.py; edit catalog/operators.json and net/*/network.json.\n"
)
SAFE_ID = re.compile(r"^[A-Za-z0-9_]+$")


def safe_path(value: str) -> Path:
    if not isinstance(value, str) or not value:
        raise ValueError(f"invalid path: {value!r}")
    path = Path(value)
    if path.is_absolute() or ".." in path.parts or "\\" in value:
        raise ValueError(f"unsafe repository path: {value!r}")
    return path


def resolve(reference: str, operators: dict) -> str:
    """Expand @operator/source[/file] or @operator/test; literals stay literal."""
    if not isinstance(reference, str):
        raise TypeError(f"invalid path reference: {reference!r}")
    if not reference.startswith("@"):
        return safe_path(reference).as_posix()
    parts = reference[1:].split("/")
    if len(parts) < 2 or parts[0] not in operators:
        raise ValueError(f"unknown operator reference: {reference}")
    operator, field, *suffix = parts
    if field not in ("source", "test", "ci_test") or field not in operators[operator]:
        raise ValueError(f"unknown operator path: {reference}")
    base = safe_path(operators[operator][field])
    return safe_path((base / Path(*suffix)).as_posix()).as_posix()


def scalar(value) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        if re.fullmatch(r"[A-Za-z0-9_./-]+", value) and value.lower() not in (
            "true",
            "false",
            "null",
            "yes",
            "no",
            "on",
            "off",
        ):
            return value
        return json.dumps(value, ensure_ascii=False)
    raise ValueError(f"unsupported YAML scalar: {value!r}")


def yaml_lines(mapping: dict) -> str:
    """Emit the small map/list/scalar subset used by existing CI readers."""
    lines = []

    def emit(obj, depth=0):
        prefix = " " * depth
        for key, value in obj.items():
            if isinstance(value, dict):
                lines.append(f"{prefix}{scalar(key)}:")
                emit(value, depth + 2)
            elif isinstance(value, list):
                if not value:
                    lines.append(f"{prefix}{scalar(key)}: []")
                else:
                    lines.append(f"{prefix}{scalar(key)}:")
                    lines.extend(f"{prefix}  - {scalar(item)}" for item in value)
            else:
                lines.append(f"{prefix}{scalar(key)}: {scalar(value)}")

    emit(mapping)
    return "\n".join(lines) + "\n"


def native_toml(exports: dict, groups: dict) -> str:
    lines = [GENERATED.rstrip(), "", "[operators]"]
    lines.extend(f"{name} = {json.dumps(files)}" for name, files in exports.items())
    lines.extend(("", "[groups]"))
    lines.extend(f"{name} = {json.dumps(ids)}" for name, ids in groups.items())
    return "\n".join(lines) + "\n"


def render(root: Path = ROOT) -> dict[Path, str]:
    catalog = json.loads((root / CATALOG).read_text(encoding="utf-8"))
    if catalog.get("schema_version") != 1:
        raise ValueError("unsupported catalog schema_version")
    operators = catalog["operators"]
    if not operators or any(not SAFE_ID.fullmatch(name) for name in operators):
        raise ValueError("operator IDs must be nonempty identifiers")
    for name, operator in operators.items():
        for field, prefix in (
            ("source", "samples"),
            ("test", "test"),
            ("ci_test", "test"),
        ):
            if field not in operator:
                if field == "source":
                    raise ValueError(f"operator {name} has no source")
                continue
            path = safe_path(operator[field])
            if path.parts[0] != prefix or not (root / path).exists():
                raise ValueError(f"operator {name} has an invalid {field}: {path}")

    policy = catalog["ci"]
    inventory = []
    for name in policy["inventory"]:
        if name not in operators:
            raise ValueError(f"unknown inventory operator: {name}")
        operator = operators[name]
        value = operator.get("inventory_path")
        if value is None:
            value = safe_path(operator["source"]).relative_to("samples").as_posix()
        inventory.append(safe_path(value).as_posix())
    if len(inventory) != len(set(inventory)):
        raise ValueError("duplicate CI inventory paths")

    config = {"skip_all_tests": policy["skip_all_tests"], "ignore": policy["ignore"]}
    if not isinstance(config["skip_all_tests"], bool):
        raise TypeError("skip_all_tests must be a boolean")
    for rule in policy["rules"]:
        name = rule["name"]
        if name in config or not isinstance(rule["enabled"], bool):
            raise ValueError(f"invalid or duplicate CI rule: {name}")
        targets = []
        for reference in rule["tests"]:
            if reference == "all":
                targets.append("all")
                continue
            path = safe_path(resolve(reference, operators))
            if path.parts[0] != "test" or not (root / path).exists():
                raise ValueError(f"invalid test target: {reference}")
            targets.append(path.relative_to("test").as_posix())
        config[name] = {
            "module": rule["enabled"],
            "src": [resolve(reference, operators) for reference in rule["watch"]],
            "options": targets,
        }

    exports = {}
    native_order = catalog["native_exports"]
    registered = {name for name, operator in operators.items() if "native" in operator}
    if len(native_order) != len(set(native_order)) or set(native_order) != registered:
        raise ValueError("native_exports must list each Native operator exactly once")
    for name in native_order:
        native = operators[name]["native"]
        export = native["export"]
        if not SAFE_ID.fullmatch(export) or export in exports:
            raise ValueError(f"invalid or duplicate Native export: {export}")
        files = []
        for reference in native["sources"]:
            source = safe_path(resolve(reference, operators))
            if (
                source.parts[0] != "samples"
                or source.suffix != ".py"
                or not (root / source).is_file()
            ):
                raise ValueError(f"invalid Native source: {reference}")
            files.append(source.relative_to("samples").as_posix())
        if not files or len(files) != len(set(files)):
            raise ValueError(f"empty or duplicate Native sources: {export}")
        exports[export] = files

    groups = {}
    for manifest in sorted((root / "net").glob("*/network.json")):
        network = json.loads(manifest.read_text(encoding="utf-8"))
        group = network["name"]
        if (
            not SAFE_ID.fullmatch(group)
            or group in groups
            or group != manifest.parent.name
        ):
            raise ValueError(f"invalid or duplicate network: {manifest}")
        ids = network["operators"]
        if not ids or len(ids) != len(set(ids)):
            raise ValueError(f"empty or duplicate network operators: {group}")
        names = []
        for name in ids:
            if name not in operators or "native" not in operators[name]:
                raise ValueError(
                    f"network {group} references an unknown Native operator: {name}"
                )
            names.append(operators[name]["native"]["export"])
        groups[group] = names

    return {
        Path("scripts/ci/operator_list.yaml"): GENERATED
        + yaml_lines({"operators": inventory}),
        Path("test/test_config.yaml"): GENERATED + yaml_lines(config),
        Path("packaging/native/operator_groups.toml"): native_toml(exports, groups),
    }


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument(
        "--write", action="store_true", help="update generated configuration files"
    )
    mode.add_argument(
        "--check", action="store_true", help="fail if configuration files are stale"
    )
    args = parser.parse_args(argv)
    try:
        outputs = render()
        stale = []
        for path, content in outputs.items():
            destination = ROOT / path
            if (
                not destination.is_file()
                or destination.read_text(encoding="utf-8") != content
            ):
                stale.append(path)
                if args.write:
                    destination.parent.mkdir(parents=True, exist_ok=True)
                    destination.write_text(content, encoding="utf-8")
        if stale and args.check:
            print(
                "Catalog views are stale: " + ", ".join(map(str, stale)),
                file=sys.stderr,
            )
            print("Run python3 scripts/ci/sync_catalog.py --write", file=sys.stderr)
            return 1
    except (KeyError, TypeError, ValueError, OSError) as error:
        print(f"Catalog error: {error}", file=sys.stderr)
        return 1
    print("Catalog configuration files are consistent.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
